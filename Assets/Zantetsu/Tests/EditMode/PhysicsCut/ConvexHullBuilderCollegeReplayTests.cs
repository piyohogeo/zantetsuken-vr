        /// <summary>
        /// **The 131-point union within the vertex limit.** Without a limit the envelope has 141 vertices (past 128; a
        /// closed hull of 141 vertices is 278 triangles, past Unity's 255 for a convex mesh). With the limit, faces are
        /// removed, the smallest first, while every input point stays inside and the expansion stays within the merge
        /// tolerance; the result is verified independently on its float output. If the limit cannot be met that way the
        /// test records the expansion it would need and fails: no wider tolerance, no inward reduction.
        /// </summary>
        [Test]
        public void CollegeUnionOf131Points_WithinTheVertexLimit()
        {
            Assert.That(ConvexHullBuilder.TryBuild(new List<float3>(k_points3), out float3[] v0, out int[] o0, out int[] i0, out HullBuildReport r0), Is.True, r0.reason);
            TestContext.Out.WriteLine("college 131 points without a limit: " + v0.Length + " v " + (o0.Length - 1) + " f (" + (2 * v0.Length - 4) + " triangles closed), expansion " + r0.expansion.ToString("E2") + " m");
            bool built = ConvexHullBuilder.TryBuild(new List<float3>(k_points3), 128, out float3[] v, out int[] offsets, out int[] indices, out HullBuildReport report);
            TestContext.Out.WriteLine("college 131 points with the limit 128: " + (built ? v.Length + " v " + (offsets.Length - 1) + " f, faces removed " + report.decimated + ", expansion " + report.expansion.ToString("E2") + " m (merge tolerance " + (ConvexHullBuilder.PlaneTolerance * report.extent).ToString("E2") + " m)" : "refused: " + report.reason));
            Assert.That(built, Is.True, "within the merge tolerance the limit is met; else what it would need: " + report.reason);
            Assert.That(v.Length, Is.LessThanOrEqualTo(128));
            HullChecks.Measure(k_points3, v, offsets, indices, out double outside, out double nonConvex, out double nonPlanar);
            TestContext.Out.WriteLine("measured here: outside " + outside.ToString("E2") + " m, non-convex " + nonConvex.ToString("E2") + " m, non-planar " + nonPlanar.ToString("E2") + " m");
            HullChecks.AssertHull(k_points3, v, offsets, indices, report, "college 131 within 128");
        }

