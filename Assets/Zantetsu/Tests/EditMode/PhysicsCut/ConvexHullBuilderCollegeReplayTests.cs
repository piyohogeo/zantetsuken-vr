            Assert.That(ConvexHullBuilder.TryBuild(new List<float3>(k_points), out float3[] v, out int[] offsets, out int[] indices, out HullBuildReport report), Is.True, report.reason);
            HullChecks.Measure(k_points, v, offsets, indices, out double outside, out double nonConvex, out double nonPlanar);
            TestContext.Out.WriteLine("college replay: " + v.Length + " v " + (offsets.Length - 1) + " f; measured here: outside " + outside.ToString("E2") + " m, non-convex " + nonConvex.ToString("E2") + " m, non-planar " + nonPlanar.ToString("E2") + " m; builder: shrink " + report.shrink.ToString("E2") + " m, expansion " + report.expansion.ToString("E2") + " m, merges " + report.merges);
            HullChecks.AssertHull(k_points, v, offsets, indices, report, "college replay");
            Assert.That(report.expansion, Is.LessThanOrEqualTo(ConvexHullBuilder.PlaneTolerance * report.extent));
        }
