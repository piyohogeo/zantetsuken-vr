            TestContext.Out.WriteLine("college replay 2: " + v.Length + " v " + (offsets.Length - 1) + " f; measured here: outside " + outside.ToString("E2") + " m, non-convex " + nonConvex.ToString("E2") + " m, non-planar " + nonPlanar.ToString("E2") + " m; builder: shrink " + report.shrink.ToString("E2") + " m, expansion " + report.expansion.ToString("E2") + " m, merges " + report.merges);
